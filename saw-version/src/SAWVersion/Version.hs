-- Version information from the build for use inside SAW.

{-# LANGUAGE Safe #-}

module SAWVersion.Version (
    versionText
  , shortVersionText
  ) where

import Paths_saw (version)
import SAWVersion.GitRev (foundGit, hash, branch)
import Data.Version (showVersion)

-- | Git branch info, in the form <hash> <branch-name>.
--
--   The git branch info is emitted into the autogenerated file
--   @GitRev.hs@ by SAW's build system. Since in practice (despite
--   various attempts to the contrary) this causes half of SAW to be
--   rebuilt every time anything git-related changes, it is possible
--   to suppress that update by setting @SAW_SUPPRESS_GITREV=yes@ in
--   the process environment. Only do that if you need it because
--   you're actively developing SAW, and be prepared to substitute
--   correct current information into any panic messages you get.
--
gitText :: String
gitText =
    if foundGit then
        case (hash, branch) of
            (Nothing, Nothing) -> "<non-dev build>"
            (Just h, Nothing) -> h ++ " <unknown-branch>"
            (Nothing, Just b) -> "<unknown-hash> " ++ b
            (Just h, Just b) -> h ++ " " ++ b
    else
        "<VCS-less build>"

-- | The version number with git branch info.
--   Has the form @1.6.0.99 (98b7423d master)@.
shortVersionText :: String
shortVersionText = showVersion version ++ " (" ++ gitText ++ ")"

-- | The version text with the word \"version\" included.
--   (Not sure why we bother to manifest this separately, especially
--   since you'd expect to want both \"version 1.6\" and \"Version 1.6\".)
versionText :: String
versionText = "version " ++ shortVersionText
